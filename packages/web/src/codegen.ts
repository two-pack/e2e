/**
 * `e2e run --codegen` for the web engine: a run's recorded agent steps as a
 * Playwright Test file.
 *
 * Each `agent.act` step becomes the Playwright calls its committed actions
 * map to, under a comment quoting the instruction. A node is addressed the way
 * the recording describes it: test id first, then role and accessible name,
 * then placeholder, text, and the structural selector, narrowed by the named
 * container it sat in and by its place among identical twins. Steps that
 * leave no actions behind (a judgment, a step the test code ran itself) are
 * kept as `TODO` comments in the order they ran, so the file reads as the
 * test did and says where a hand still has to fill in an assertion.
 *
 * The output is a starting point for a Playwright suite, not a replay: an
 * agent step that adapted to the screen is frozen at what it did in this run.
 */

import type { CodegenAction, CodegenFile, CodegenStep, CodegenTargetDescriptor, CodegenTest, EngineCodegen } from 'e2e/engine';

/** The roles `page.getByRole` takes that the engine's tree also reports; anything else falls back to text or selector. */
const ARIA_ROLES: ReadonlySet<string> = new Set([
  'alert', 'alertdialog', 'application', 'article', 'banner', 'blockquote', 'button', 'caption', 'cell', 'checkbox',
  'code', 'columnheader', 'combobox', 'complementary', 'contentinfo', 'definition', 'deletion', 'dialog', 'directory',
  'document', 'emphasis', 'feed', 'figure', 'form', 'generic', 'grid', 'gridcell', 'group', 'heading', 'img',
  'insertion', 'link', 'list', 'listbox', 'listitem', 'log', 'main', 'marquee', 'math', 'meter', 'menu', 'menubar',
  'menuitem', 'menuitemcheckbox', 'menuitemradio', 'navigation', 'none', 'note', 'option', 'paragraph', 'presentation',
  'progressbar', 'radio', 'radiogroup', 'region', 'row', 'rowgroup', 'rowheader', 'scrollbar', 'search', 'searchbox',
  'separator', 'slider', 'spinbutton', 'status', 'strong', 'subscript', 'superscript', 'switch', 'tab', 'table',
  'tablist', 'tabpanel', 'term', 'textbox', 'time', 'timer', 'toolbar', 'tooltip', 'tree', 'treegrid', 'treeitem',
]);

/**
 * The containers a recorded `within` key names (`containerKey` in the runner:
 * row, list item, article, group, region, dialog, tab panel), as CSS. The key
 * is the container's first text, so of the nested containers holding it the
 * innermost, the last in document order, is the one the node sat in.
 */
const CONTAINER_SELECTOR =
  ':is(tr, [role=row], li, [role=listitem], article, [role=article], fieldset, [role=group], section, [role=region], dialog, [role=dialog], [role=tabpanel])';

/** How far one recorded `scroll` moves, in CSS pixels: about a screen, as the agent's own scroll does. */
const SCROLL_STEP_PX = 600;

/** The Playwright test id attribute; a different one is set at the top of the file. */
const PLAYWRIGHT_TEST_ID_ATTRIBUTE = 'data-testid';

/** The `codegen` member of the web engine, writing Playwright Test files for the run's test id attribute. */
export function playwrightCodegen(testIdAttribute: string | undefined): EngineCodegen {
  return {
    extension: '.spec.ts',
    render: (file) => renderFile(file, testIdAttribute ?? PLAYWRIGHT_TEST_ID_ATTRIBUTE),
  };
}

/** What rendering one file learned that its header has to provide. */
interface FileNeeds {
  secrets: boolean;
  within: boolean;
  testIdAttribute: boolean;
}

/** Renders one test file's passing tests as a Playwright Test file. */
function renderFile(file: CodegenFile, testIdAttribute: string): string {
  const needs: FileNeeds = { secrets: false, within: false, testIdAttribute: false };
  const body = renderTree(buildTree(file.tests), 0, file, needs);
  const imports = [
    `import { ${needs.testIdAttribute ? 'selectors, test' : 'test'} } from "@playwright/test";`,
    ...(needs.within ? ['import type { Locator, Page } from "@playwright/test";'] : []),
  ];
  const header = [
    `// Generated by \`e2e run --codegen\` from ${file.file} (target "${oneLine(file.target)}").`,
    '// Each block is what an agent step did in that run, frozen: review it, then replace the',
    '// TODO comments with the assertions the e2e test made through the agent.',
    ...imports,
    '',
    ...(needs.testIdAttribute ? [`selectors.setTestIdAttribute(${literal(testIdAttribute)});`, ''] : []),
    ...(file.appUrl === undefined ? [] : [`test.use({ baseURL: process.env["BASE_URL"] ?? ${literal(file.appUrl)} });`, '']),
    ...(needs.secrets ? SECRET_HELPER : []),
    ...(needs.within ? WITHIN_HELPER : []),
  ];
  return `${[...header, ...body].join('\n').trimEnd()}\n`;

  function renderTree(node: TreeNode, depth: number, source: CodegenFile, state: FileNeeds): string[] {
    const lines: string[] = [];
    for (const child of node.children) {
      if (lines.length > 0) lines.push('');
      if (child.kind === 'test') {
        lines.push(...renderTest(child.test, depth, source, state));
        continue;
      }
      lines.push(`${indent(depth)}test.describe(${literal(child.title)}, () => {`);
      lines.push(...renderTree(child, depth + 1, source, state));
      lines.push(`${indent(depth)}});`);
    }
    return lines;
  }

  function renderTest(test: CodegenTest, depth: number, source: CodegenFile, state: FileNeeds): string[] {
    const lines = [`${indent(depth)}test(${literal(test.title)}, async ({ page }) => {`];
    const writer = new StepWriter(source, testIdAttribute, state);
    for (const step of test.steps) writer.step(step);
    lines.push(...writer.lines.map((line) => (line === '' ? '' : `${indent(depth + 1)}${line}`)));
    lines.push(`${indent(depth)}});`);
    return lines;
  }
}

/** Reads a secret from the variable that overrides it in the e2e config; see `secretVariable`. */
const SECRET_HELPER = [
  '/** A secret the agent filled, read from the environment; the generated file never holds its value. */',
  'function secret(variable: string): string {',
  '  const value = process.env[variable];',
  '  if (value === undefined) throw new Error(`set ${variable} to run this test`);',
  '  return value;',
  '}',
  '',
];

/**
 * The environment variable that overrides a secret in the e2e config: a
 * credential's password (`<credential>.password`) is `E2E_USER_<CREDENTIAL>_PASSWORD`,
 * any other secret `E2E_SECRET_<NAME>`, each name uppercased with everything
 * outside A-Z and 0-9 as `_`, as the config resolves them.
 */
function secretVariable(name: string): string {
  const upper = (value: string): string => value.toUpperCase().replaceAll(/[^A-Z0-9]/g, '_');
  return name.endsWith(CREDENTIAL_PASSWORD_SUFFIX)
    ? `E2E_USER_${upper(name.slice(0, -CREDENTIAL_PASSWORD_SUFFIX.length))}_PASSWORD`
    : `E2E_SECRET_${upper(name)}`;
}

/** How the config names a credential's password secret: `<credential>.password`. */
const CREDENTIAL_PASSWORD_SUFFIX = '.password';

/**
 * Scopes a locator to the container the agent found its node in, by the
 * container's first text. Nested containers holding the key come outermost
 * first in document order, so the last one is the node's own.
 */
const WITHIN_HELPER = [
  '/** The innermost row, list item, group, region, or dialog whose text includes `key`: where the agent found the element. */',
  'function within(page: Page, key: string): Locator {',
  `  return page.locator(${literal(CONTAINER_SELECTOR)}).filter({ hasText: key }).last();`,
  '}',
  '',
];

/** The describe tree of one file, from each test's title path. */
type TreeNode = { readonly kind: 'describe'; readonly title: string; readonly children: (TreeNode | TestLeaf)[] };
type TestLeaf = { readonly kind: 'test'; readonly test: CodegenTest };

function buildTree(tests: readonly CodegenTest[]): TreeNode {
  const root: TreeNode = { kind: 'describe', title: '', children: [] };
  for (const test of tests) {
    // The title path ends with the test's own title; what comes before it are describes.
    const describes = test.titlePath.at(-1) === test.title ? test.titlePath.slice(0, -1) : test.titlePath;
    let node = root;
    for (const title of describes) {
      let next = node.children.find((child): child is TreeNode => child.kind === 'describe' && child.title === title);
      if (next === undefined) {
        next = { kind: 'describe', title, children: [] };
        node.children.push(next);
      }
      node = next;
    }
    node.children.push({ kind: 'test', test });
  }
  return root;
}

/** Writes one test's steps, tracking where the page is so a step that starts elsewhere opens it first. */
class StepWriter {
  readonly lines: string[] = [];
  /** Whether anything so far put the page on a location: a navigation, an opened app, a recorded act. */
  private navigated = false;

  constructor(
    private readonly file: CodegenFile,
    private readonly testIdAttribute: string,
    private readonly needs: FileNeeds,
  ) {}

  step(step: CodegenStep): void {
    if (this.lines.length > 0) this.lines.push('');
    const where = step.line === undefined ? '' : ` (${this.file.file}:${String(step.line)})`;
    if (step.recording === undefined) {
      this.other(step, where);
      return;
    }
    this.lines.push(`// ${step.api}: ${oneLine(step.label)}${where}`);
    if (step.recording.incomplete) {
      this.lines.push('// NOTE: this step was not recorded whole (a secret in a value, an action over the cap, or a node with');
      this.lines.push('// nothing durable to find it by); check the calls below against the run.');
    }
    const first = step.recording.actions[0];
    if (!this.navigated && step.recording.startLocation !== undefined && first?.name !== 'navigate') {
      this.lines.push(`await page.goto(${literal(this.relative(step.recording.startLocation))});`);
    }
    this.navigated = true;
    for (const action of step.recording.actions) this.lines.push(...this.action(action));
  }

  /** A step with no recorded actions: an opened app becomes a `goto`, anything else a TODO in its place. */
  private other(step: CodegenStep, where: string): void {
    if (step.api === 'app.open') {
      const url = step.label.trim();
      this.lines.push(`// ${step.api}${where}`);
      this.lines.push(`await page.goto(${literal(url === '' ? '/' : url)});`);
      this.navigated = true;
      return;
    }
    const judgment = step.api.startsWith('agent.') && step.api !== 'agent.act';
    const todo = judgment
      ? `TODO: ${step.api} was a model judgment; write it as an expect() on what it checked`
      : step.api === 'agent.act'
        ? 'TODO: agent.act committed no action this code can repeat'
        : `TODO: ${step.api} ran as test code; port it by hand`;
    this.lines.push(`// ${step.api}: ${oneLine(step.label)}${where}`);
    this.lines.push(`// ${todo}`);
  }

  /** The Playwright statements one recorded action maps to. */
  private action(action: CodegenAction): string[] {
    switch (action.name) {
      case 'tap':
        return [`await ${this.locator(action.target)}.click();`];
      case 'doubleTap':
        return [`await ${this.locator(action.target)}.dblclick();`];
      case 'longPress':
        return [`await ${this.locator(action.target)}.click({ delay: 1000 });`];
      case 'secondaryTap':
        return [`await ${this.locator(action.target)}.click({ button: "right" });`];
      case 'hover':
        return [`await ${this.locator(action.target)}.hover();`];
      case 'scrollTo':
        return [`await ${this.locator(action.target)}.scrollIntoViewIfNeeded();`];
      case 'type':
        return [`await ${this.locator(action.target)}.fill(${literal(action.value)});`];
      case 'typeSecret':
        this.needs.secrets = true;
        return [`await ${this.locator(action.target)}.fill(secret(${literal(secretVariable(action.secret))}));`];
      case 'press':
        return [`await ${this.locator(action.target)}.press(${literal(action.key)});`];
      case 'select':
        return [`await ${this.locator(action.target)}.selectOption(${literal(action.value)});`];
      case 'check':
        return [`await ${this.locator(action.target)}.setChecked(${String(action.checked)});`];
      case 'upload':
        return [
          '// Paths are relative to the e2e project root.',
          `await ${this.locator(action.target)}.setInputFiles(${literal(action.paths)});`,
        ];
      case 'drag':
        return [`await ${this.locator(action.target)}.dragTo(${this.locator(action.destination)});`];
      case 'scroll':
        return this.scroll(action.direction, action.target, action.times ?? 1);
      case 'scrollUntil':
        return [`await page.getByText(${literal(action.text)}).first().scrollIntoViewIfNeeded();`];
      case 'navigate':
        return [`await page.goto(${literal(this.relative(action.url))});`];
      case 'back':
        return ['await page.goBack();'];
      case 'tapAt':
      case 'hoverAt': {
        const verb = action.name === 'tapAt' ? 'click' : 'move';
        if (action.within !== undefined) {
          return [
            '{',
            `  const box = await ${this.locator(action.within.target)}.boundingBox();`,
            '  if (box === null) throw new Error("the element the agent pointed into is not visible");',
            `  await page.mouse.${verb}(box.x + box.width * ${String(action.within.fx)}, box.y + box.height * ${String(action.within.fy)});`,
            '}',
          ];
        }
        return [
          `// A bare point on the ${String(action.viewport.width)}x${String(action.viewport.height)} viewport the run used.`,
          `await page.mouse.${verb}(${String(action.point.x)}, ${String(action.point.y)});`,
        ];
      }
      case 'typeText':
        return [
          ...(action.replace ? ['await page.keyboard.press("ControlOrMeta+A");'] : []),
          `await page.keyboard.type(${literal(action.value)});`,
        ];
      case 'pressKey':
        return [`await page.keyboard.press(${literal(action.key)});`];
      case 'dismissKeyboard':
        return [];
      case 'tool':
        return [
          action.derived === undefined
            ? `// TODO: ${oneLine(action.summary)}: a project tool the agent called; repeat it here by hand.`
            : `// TODO: the agent typed a value this run read off the screen (${action.derived}); type it here by hand.`,
        ];
    }
  }

  private scroll(direction: 'up' | 'down' | 'left' | 'right', target: CodegenTargetDescriptor | undefined, times: number): string[] {
    const delta = SCROLL_STEP_PX * times;
    const [dx, dy] =
      direction === 'down' ? [0, delta] : direction === 'up' ? [0, -delta] : direction === 'right' ? [delta, 0] : [-delta, 0];
    return [
      ...(target === undefined ? [] : [`await ${this.locator(target)}.hover();`]),
      `await page.mouse.wheel(${String(dx)}, ${String(dy)});`,
    ];
  }

  /** A Playwright locator expression for a recorded node, most durable field first. */
  private locator(target: CodegenTargetDescriptor): string {
    if (target.within !== undefined) this.needs.within = true;
    const scope = target.within === undefined ? 'page' : `within(page, ${literal(target.within)})`;
    let base: string;
    if (target.testId !== undefined) {
      if (this.testIdAttribute !== PLAYWRIGHT_TEST_ID_ATTRIBUTE) this.needs.testIdAttribute = true;
      base = `${scope}.getByTestId(${literal(target.testId)})`;
    } else if (target.role !== undefined && ARIA_ROLES.has(target.role) && target.name !== undefined) {
      base = `${scope}.getByRole(${literal(target.role)}, { name: ${literal(target.name)}, exact: true })`;
    } else if (target.placeholder !== undefined) {
      base = `${scope}.getByPlaceholder(${literal(target.placeholder)}, { exact: true })`;
    } else if (target.selector !== undefined) {
      base = `${scope}.locator(${literal(target.selector)})`;
    } else if (target.name !== undefined || target.text !== undefined) {
      base = `${scope}.getByText(${literal((target.name ?? target.text)!)}, { exact: true })`;
    } else if (target.role !== undefined && ARIA_ROLES.has(target.role)) {
      base = `${scope}.getByRole(${literal(target.role)})`;
    } else {
      base = `${scope}.locator(':focus') /* TODO: the recording kept nothing to find this node by */`;
    }
    return target.position !== undefined && target.position.of > 1 ? `${base}.nth(${String(target.position.index)})` : base;
  }

  /** A location on the app's own origin as a path the `baseURL` resolves; any other location whole. */
  private relative(location: string): string {
    if (this.file.appUrl === undefined) return location;
    let app: URL;
    let target: URL;
    try {
      app = new URL(this.file.appUrl);
      target = new URL(location, app);
    } catch {
      return location;
    }
    return target.origin === app.origin ? `${target.pathname}${target.search}${target.hash}` : target.href;
  }
}

/** A JavaScript literal for a string or a list of strings. */
function literal(value: string | readonly string[]): string {
  return JSON.stringify(value);
}

/** Text on one comment line: whitespace collapsed, so a newline in a label cannot end the comment. */
function oneLine(text: string): string {
  return text.replaceAll(/\s+/g, ' ').trim();
}

function indent(depth: number): string {
  return '  '.repeat(depth);
}
