/**
 * `e2e run --codegen` for the web engine: a run's tests as a Playwright Test
 * file that runs without a model.
 *
 * The test file's own source is converted (`codegen-source.ts`): every
 * `agent.*` call becomes what the agent did or checked in the run, and the
 * rest of the e2e API its Playwright spelling, control flow and helpers kept.
 * When the source cannot be read or parsed, the recorded steps are written
 * out on their own instead, one test per passing test, with the steps the
 * run did not record as comments in their place.
 */

import type { CodegenFile, CodegenRendered, CodegenStep, CodegenTest, EngineCodegen } from 'e2e/engine';
import { convertSource } from './codegen-source.ts';
import { gapComments, gapMarker, literal, locateOnScreen, oneLine, PLAYWRIGHT_TEST_ID_ATTRIBUTE, StatementWriter, takeGapLines } from './codegen-statements.ts';

/** e2e's default judgment timeout, the deadline a `waitFor` check retries until in the fallback. */
const DEFAULT_JUDGMENT_TIMEOUT = '30_000';

/** The `codegen` member of the web engine, writing Playwright Test files for the run's test id attribute. */
export function playwrightCodegen(testIdAttribute: string | undefined): EngineCodegen {
  const attribute = testIdAttribute ?? PLAYWRIGHT_TEST_ID_ATTRIBUTE;
  return {
    // `.gen` marks the file as written by e2e; `.spec` is the name Playwright Test picks up by default.
    extension: '.gen.spec.ts',
    render: (file) => convertSource(file, attribute) ?? renderSteps(file, attribute),
    locate: locateOnScreen,
  };
}

/** The fallback: the recorded steps of each passing test, in a describe tree from their title paths. */
function renderSteps(file: CodegenFile, testIdAttribute: string): CodegenRendered {
  const writer = new StatementWriter(testIdAttribute, file.appUrl);
  const gaps: { readonly test: number; readonly step: number }[] = [];
  const body = renderTree(buildTree(file.tests), 0);
  const header = [
    `// Generated by \`e2e run --codegen\` from ${file.file} (target "${oneLine(file.target)}").`,
    '// The test source could not be read, so this file holds the recorded steps alone; the steps the',
    '// test code ran itself are comments where they ran.',
    ...writer.imports(),
    '',
    ...(file.appUrl === undefined ? [] : [`test.use({ baseURL: process.env["BASE_URL"] ?? ${literal(file.appUrl)} });`, '']),
    ...writer.helpers(),
  ];
  const { code, lines: gapLines } = takeGapLines(`${[...header, ...body].join('\n').trimEnd()}\n`);
  return {
    code,
    gaps: gaps.flatMap((gap, index) => {
      const line = gapLines.get(index);
      return line === undefined ? [] : [{ ...gap, line }];
    }),
  };

  function renderTree(node: TreeNode, depth: number): string[] {
    const lines: string[] = [];
    for (const child of node.children) {
      if (lines.length > 0) lines.push('');
      if (child.kind === 'test') {
        lines.push(...renderTest(child.test, depth));
        continue;
      }
      lines.push(`${indent(depth)}test.describe(${literal(child.title)}, () => {`, ...renderTree(child, depth + 1), `${indent(depth)}});`);
    }
    return lines;
  }

  function renderTest(test: CodegenTest, depth: number): string[] {
    const statements: string[] = [];
    const testIndex = file.tests.indexOf(test);
    for (const [index, step] of test.steps.entries()) {
      if (statements.length > 0) statements.push('');
      const written = stepStatements(step, file, writer);
      if (step.judgment?.gap !== undefined && written.length > 0) {
        gaps.push({ test: testIndex, step: index });
        written[0] = `${gapMarker(gaps.length - 1)}${written[0]!}`;
      }
      statements.push(...written);
    }
    return [
      `${indent(depth)}test(${literal(test.title)}, async ({ page }) => {`,
      ...statements.map((line) => (line === '' ? '' : `${indent(depth + 1)}${line}`)),
      `${indent(depth)}});`,
    ];
  }
}

/** The statements one recorded step becomes in the fallback. */
function stepStatements(step: CodegenStep, file: CodegenFile, writer: StatementWriter): string[] {
  const where = step.line === undefined ? '' : ` (${file.file}:${String(step.line)})`;
  const header = `// ${step.api}: ${oneLine(step.label)}${where}`;
  if (step.recording !== undefined) {
    return [
      header,
      ...(step.recording.incomplete
        ? ['// NOTE: this step was not recorded whole (a secret in a value, an action over the cap, or a node', '// with nothing durable to find it by); check the calls below against the run.']
        : []),
      ...step.recording.actions.flatMap((action) => writer.action(action)),
    ];
  }
  const gap = step.judgment?.gap;
  if (step.judgment !== undefined && step.judgment.checks.length > 0) {
    const timeout = step.api === 'agent.waitFor' ? DEFAULT_JUDGMENT_TIMEOUT : undefined;
    return [
      header,
      ...(step.judgment.value === undefined ? [] : [`// Returned ${literal(step.judgment.value)}.`]),
      ...(gap === undefined ? [] : gapComments(gap, true)),
      ...step.judgment.checks.map((check) => writer.check(check, timeout)),
    ];
  }
  if (step.api === 'app.open') return [`// ${step.api}${where}`, `await page.goto(${literal(step.label.trim() === '' ? '/' : step.label.trim())});`];
  if (step.api === 'agent.act') return [header, '// The agent found nothing to do here in the recorded run.'];
  if (step.api.startsWith('agent.')) {
    return [header, '// TODO: no deterministic check could be derived from the screen this judgment passed on.', ...(gap === undefined ? [] : gapComments(gap, false).slice(1))];
  }
  return [header, `// TODO: ${step.api} ran as test code; the test source could not be read to carry it over.`];
}

/** The describe tree of one file, from each test's title path. */
type TreeNode = { readonly kind: 'describe'; readonly title: string; readonly children: (TreeNode | TestLeaf)[] };
type TestLeaf = { readonly kind: 'test'; readonly test: CodegenTest };

function buildTree(tests: readonly CodegenTest[]): TreeNode {
  const root: TreeNode = { kind: 'describe', title: '', children: [] };
  for (const test of tests) {
    // The title path ends with the test's own title; what comes before it are describes.
    const describes = test.titlePath.at(-1) === test.title ? test.titlePath.slice(0, -1) : test.titlePath;
    let node = root;
    for (const title of describes) {
      let next = node.children.find((child): child is TreeNode => child.kind === 'describe' && child.title === title);
      if (next === undefined) {
        next = { kind: 'describe', title, children: [] };
        node.children.push(next);
      }
      node = next;
    }
    node.children.push({ kind: 'test', test });
  }
  return root;
}

function indent(depth: number): string {
  return '  '.repeat(depth);
}
